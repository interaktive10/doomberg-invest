#!/usr/bin/env python3
"""Resolve the Capex Desk seed against the universe snapshots (BRIEF §1.3, Appendix H, §8 M0-05).

Offline: reads data/universe/*.  Writes docs/UNIVERSE_ISSUES.md listing every name that is not confirmed.
With --write, flips `verified: true` in config/capex_seed.yaml for India symbols found in the NSE EQ list.
Exit 0 always (unresolved names are documented, not fatal); --strict exits 1 if anything is unresolved.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from pipeline.india.securities import load_snapshot as load_nse  # noqa: E402
from pipeline.india.securities import parse_equity_list  # noqa: E402
from pipeline.us.universe import load_snapshot as load_sec  # noqa: E402

SEED = ROOT / "config" / "capex_seed.yaml"
US_SNAP = ROOT / "data" / "universe" / "us_tickers_exchange.json"
IN_SNAP = ROOT / "data" / "universe" / "nse_equity_list.csv"
ISSUES = ROOT / "docs" / "UNIVERSE_ISSUES.md"


@dataclass
class Resolution:
    us_total: int = 0
    in_total: int = 0
    us_unresolved: list[str] = field(default_factory=list)
    in_unresolved: list[tuple[str, str, str]] = field(default_factory=list)  # (name, proposed symbol, reason)
    in_resolved: list[str] = field(default_factory=list)
    us_snapshot: bool = False
    in_snapshot: bool = False

    @property
    def unresolved(self) -> int:
        return len(self.us_unresolved) + len(self.in_unresolved)


def resolve(
    seed: dict[str, Any],
    us_tickers: set[str] | None,
    nse_symbols: dict[str, str] | None,
    nse_other_series: dict[str, str] | None = None,
) -> Resolution:
    """nse_symbols: EQ symbol -> name. nse_other_series: symbol -> series for listings outside EQ (e.g. BE)."""
    r = Resolution(us_snapshot=us_tickers is not None, in_snapshot=nse_symbols is not None)
    for group in seed["us"].values():
        for t in group:
            r.us_total += 1
            if us_tickers is None:
                r.us_unresolved.append(f"{t} (no SEC snapshot yet)")
            elif t not in us_tickers:
                r.us_unresolved.append(f"{t} (not a NYSE/Nasdaq ticker in the SEC snapshot)")
    for e in seed["india"]:
        r.in_total += 1
        sym = str(e.get("nse") or "")
        if nse_symbols is None:
            r.in_unresolved.append((e["name"], sym, "no NSE snapshot yet; symbol proposed from knowledge, unverified"))
        elif sym in nse_symbols:
            r.in_resolved.append(sym)
        elif nse_other_series and sym in nse_other_series:
            r.in_unresolved.append(
                (
                    e["name"],
                    sym,
                    f"listed on NSE in series {nse_other_series[sym]}, not EQ; outside the BRIEF §1.3 India universe",
                )
            )
        else:
            r.in_unresolved.append((e["name"], sym, "proposed symbol not in NSE EQ list"))
    return r


def render_issues(r: Resolution) -> str:
    lines = [
        "# Universe issues",
        "",
        "Generated by `scripts/resolve_capex_seed.py` (BRIEF §1.3, Appendix H). Names here are not yet confirmed "
        "against the universe snapshots in `data/universe/`.",
        "",
        f"- US capex seed: {r.us_total} tickers, {len(r.us_unresolved)} unresolved"
        + ("" if r.us_snapshot else " (SEC snapshot missing)"),
        f"- India capex seed: {r.in_total} names, {len(r.in_resolved)} verified, {len(r.in_unresolved)} unresolved"
        + ("" if r.in_snapshot else " (NSE snapshot missing)"),
        "",
    ]
    if not (r.us_snapshot and r.in_snapshot):
        lines += [
            "**Why unresolved:** a snapshot is missing from `data/universe/`. Fix: run the `universe` GitHub Actions "
            "workflow (it fetches on a runner and commits the files; SEC throttles the shared IP of cloud sessions), "
            "or `make universe` where sec.gov and nseindia.com are reachable.",
            "",
        ]
    if r.us_unresolved:
        lines += ["## US", "", *[f"- {u}" for u in r.us_unresolved], ""]
    if r.in_unresolved:
        lines += ["## India", "", "| Name | Proposed NSE symbol | Reason |", "|---|---|---|"]
        lines += [f"| {n} | `{s}` | {why} |" for n, s, why in r.in_unresolved]
        lines.append("")
    return "\n".join(lines)


def mark_verified(text: str, symbols: set[str]) -> str:
    def sub(m: re.Match[str]) -> str:
        return m.group(0).replace("verified: false", "verified: true") if m.group(1) in symbols else m.group(0)

    return re.sub(r"nse: ([^,}]+), verified: false", sub, text)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--strict", action="store_true")
    a = ap.parse_args(argv)
    seed: dict[str, Any] = yaml.safe_load(SEED.read_text(encoding="utf-8"))
    us = {t for f in load_sec(US_SNAP) for t in f.tickers} if US_SNAP.exists() else None
    nse = {s.symbol: s.name for s in load_nse(IN_SNAP)} if IN_SNAP.exists() else None
    other = (
        {s.symbol: s.series for s in parse_equity_list(IN_SNAP.read_bytes(), series=None) if s.series != "EQ"}
        if IN_SNAP.exists()
        else None
    )
    r = resolve(seed, us, nse, other)
    ISSUES.write_text(render_issues(r), encoding="utf-8")
    if a.write and r.in_resolved:
        SEED.write_text(mark_verified(SEED.read_text(encoding="utf-8"), set(r.in_resolved)), encoding="utf-8")
    print(
        f"capex seed: US {r.us_total - len(r.us_unresolved)}/{r.us_total}, "
        f"India {len(r.in_resolved)}/{r.in_total} resolved; issues -> docs/UNIVERSE_ISSUES.md"
    )
    return 1 if a.strict and r.unresolved else 0


if __name__ == "__main__":
    sys.exit(main())
